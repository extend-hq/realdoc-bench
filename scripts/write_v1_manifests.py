def write_manifest(folder: Path, rows: list[tuple[str, str, str, str, str]]) -> None:
    manifest = folder / "_sources_manifest.csv"
    sources = folder / "sources"
    if not sources.exists():
        print(f"[skip] missing sources/ in {folder.name}")
        return
    on_disk = {p.name for p in sources.glob("*.pdf")}
    rows_present = [r for r in rows if r[0] in on_disk]
    extras = sorted(on_disk - {r[0] for r in rows_present})
    with manifest.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS, quoting=csv.QUOTE_ALL)
        w.writeheader()
        for fname, url, site, filled, notes in rows_present:
            w.writerow({
                "local_filename": fname,
                "source_url": url,
                "source_site": site,
                "is_filled": filled,
                "doc_pages": "",  # populated by update_sources_manifest.py
                "downloaded_on": TODAY,
                "notes": notes,
            })
        for fname in extras:
            w.writerow({
                "local_filename": fname,
                "source_url": "",
                "source_site": "",
                "is_filled": "unknown",
                "doc_pages": "",
                "downloaded_on": TODAY,
                "notes": "[on disk but not in catalog]",
            })
    print(f"[ok]  {folder.name}: wrote {len(rows_present)} catalog rows + {len(extras)} extras")


def main() -> int:
    for folder_name, rows in CATALOG.items():
        write_manifest(DATASETS / folder_name, rows)

    # Then refresh page counts
    print()
    print("Refreshing page counts via update_sources_manifest.py …")
    subprocess.check_call([
        sys.executable,
        str(REPO / "scripts/update_sources_manifest.py"),
    ])
    return 0


if __name__ == "__main__":
    sys.exit(main())
