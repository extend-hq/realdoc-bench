#!/usr/bin/env python3
"""Evaluate filled synthetic PDFs against their source blanks on three rubrics.

Rubrics (each 1-10):
  A. FORM FIDELITY     — does the filled doc preserve the source form's layout,
                         ink color, label wording, box borders, form variant?
  B. SIGNATURE REALISM — do signatures look hand-signed (cursive, blue ink,
                         pressure variation) vs printed text?
  C. CHECKBOX SANITY   — only checked where data warrants, hand-drawn marks,
                         no every-box-checked / no-box-checked failure modes.

Uses Claude Sonnet 4.5 vision: sends source page-1 + filled page-1 + structured
prompt asking for JSON. Parallel via ThreadPoolExecutor.

Output:
  - runs/eval_filled/<timestamp>/grades.csv
  - runs/eval_filled/<timestamp>/grades.md  (sorted table + per-doc reasoning)

Usage:
  python -u scripts/eval_filled_docs.py
  python -u scripts/eval_filled_docs.py --type v1_cms_1500
  python -u scripts/eval_filled_docs.py --workers 6 --limit 5  # smoke
"""

from __future__ import annotations

import argparse
import base64
import csv
import io
import json
import os
import re
import sys
import time
from concurrent.futures import ThreadPoolExecutor, as_completed
from dataclasses import dataclass, asdict
from datetime import datetime
from pathlib import Path

import fitz

REPO = Path(__file__).resolve().parent.parent
DATASETS = REPO / "datasets" / "extraction"
RUNS = REPO / "runs" / "eval_filled"

# (type_dir, filled_suffix)
SCOPE = [
    ("v1_cms_1500", "_cmsfill.pdf"),
    ("v1_vaers", "_v2fill.pdf"),
    ("v1_ub04", "_v2fill.pdf"),
    ("v1_form_5500", "_v2fill.pdf"),
]


def load_dotenv(path: Path = REPO / ".env") -> None:
    if not path.exists():
        return
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        if line.startswith("export "):
            line = line[len("export "):]
        k, v = line.split("=", 1)
        v = v.strip().strip('"').strip("'")
        if k and v and not os.environ.get(k):
            os.environ[k] = v
load_dotenv()


_anthropic = None
def get_anthropic():
    global _anthropic
    if _anthropic is None:
        from anthropic import Anthropic
        _anthropic = Anthropic(api_key=os.environ.get("ANTHROPIC_API_KEY"))
    return _anthropic


# =====================================================================

RUBRIC_PROMPT = """You are evaluating a synthetic FILLED form against its ORIGINAL BLANK source on three quality rubrics. Both images are page 1 of PDFs.

Image 1 = ORIGINAL BLANK source form (or lightly-pre-filled if the source itself had some text — focus on PRINTED FORM ELEMENTS: layout, labels, ink color, borders, headers/footers, official seals, box numbering).

Image 2 = FILLED version generated by an image-edit model. It should look IDENTICAL to image 1 except that blank fields now have typed/written values.

Score each rubric 1-10 (10 = perfect, 1 = total failure):

A. FORM FIDELITY
   - 10 = pixel-perfect preservation of the original form (every printed label, sub-label, instruction line, box border, line weight, ink color, header/footer text, official seals, OMB/version numbers, watermarks all intact); the only difference is added typed values.
   - 7-9 = preserved with minor distortions (font slightly off, faint label changes, tiny color shifts).
   - 4-6 = recognizable as same form family but visibly redesigned/cleaned (form variant may have regressed to an older or simplified version, ink color shifted, label text paraphrased).
   - 1-3 = completely regenerated as a different-looking form, wrong variant entirely, or hallucinated content.

B. SIGNATURE REALISM (skip if no signature fields are visible — return 0 with reasoning "no signature field")
   - 10 = realistic hand-signed cursive, varied stroke pressure, blue ink, looks like a real signature.
   - 7-9 = cursive-looking but stiff or uniformly pressured, plausible color.
   - 4-6 = printed-script font masquerading as signature, or signature in black/wrong color.
   - 1-3 = printed text in signature box, or no attempt at handwriting.
   - 0 = no signature field on this page (not applicable).

C. CHECKBOX CORRECTNESS
   - 10 = only the checkboxes appropriate to the persona are checked (mutually-exclusive options pick ONE, Yes/No picks ONE, list of conditions picks SPARSELY), with hand-drawn X or ✓ in pen.
   - 7-9 = mostly right but minor over/under-checking, or marks are printed-style not hand-drawn.
   - 4-6 = noticeable over-checking (e.g. both Yes AND No in same group, or 3-of-3 options in a mutually-exclusive group).
   - 1-3 = every checkbox on the page is checked, OR no checkboxes are checked at all when data is present.
   - 0 = no checkboxes on this page (not applicable).

Output ONLY a single JSON object, no preamble or fences:
{
  "form_fidelity": <int 1-10>,
  "signature_realism": <int 0-10>,
  "checkbox_correctness": <int 0-10>,
  "overall_grade": <int 1-10>,
  "reasoning": "<2-3 sentence justification covering all three rubrics; cite specific visible elements>"
}
"""


def render_page_b64(pdf: Path, page_idx: int = 0, dpi: int = 110) -> str:
    """Render a PDF page as base64-encoded PNG."""
    with fitz.open(pdf) as doc:
        page = doc[page_idx if page_idx < doc.page_count else 0]
        mat = fitz.Matrix(dpi / 72, dpi / 72)
        pix = page.get_pixmap(matrix=mat, alpha=False)
        png = pix.tobytes("png")
    return base64.b64encode(png).decode()


def grade_one(source_pdf: Path, filled_pdf: Path, model: str) -> dict:
    """Single VLM call comparing source vs filled."""
    src_b64 = render_page_b64(source_pdf)
    fil_b64 = render_page_b64(filled_pdf)
    client = get_anthropic()
    resp = client.messages.create(
        model=model,
        max_tokens=1200,
        messages=[{
            "role": "user",
            "content": [
                {"type": "image", "source": {"type": "base64", "media_type": "image/png", "data": src_b64}},
                {"type": "image", "source": {"type": "base64", "media_type": "image/png", "data": fil_b64}},
                {"type": "text", "text": RUBRIC_PROMPT},
            ],
        }],
    )
    text = resp.content[0].text.strip()
    if text.startswith("```"):
        text = re.sub(r"^```(?:json)?\s*\n?", "", text)
        text = re.sub(r"\n?```\s*$", "", text)
    # Attempt to find JSON envelope
    m = re.search(r"\{.*\}", text, re.DOTALL)
    if m:
        text = m.group(0)
    return json.loads(text)


def find_source(filled_pdf: Path, type_dir: Path, filled_suffix: str) -> Path | None:
    """filled name: <base>__pNN_<suffix>  →  source: sources/<base>.pdf"""
    base = filled_pdf.name
    if not base.endswith(filled_suffix):
        return None
    base = base[:-len(filled_suffix)]
    base = re.sub(r"__p\d+$", "", base)
    candidate = type_dir / "sources" / f"{base}.pdf"
    return candidate if candidate.exists() else None


@dataclass
class GradeRow:
    type: str
    filled_filename: str
    source_filename: str
    form_fidelity: int
    signature_realism: int
    checkbox_correctness: int
    overall_grade: int
    reasoning: str
    error: str = ""

    def display_name(self) -> str:
        return f"{self.type}/{self.filled_filename}"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--type", action="append", help="Restrict to one or more types")
    ap.add_argument("--workers", type=int, default=6)
    ap.add_argument("--limit", type=int, default=None, help="Smoke: only N docs total")
    ap.add_argument("--model", default="claude-sonnet-4-5")
    args = ap.parse_args()

    # Build work list
    work: list[tuple[str, Path, Path]] = []
    for type_name, suffix in SCOPE:
        if args.type and type_name not in args.type:
            continue
        type_dir = DATASETS / type_name
        synth = type_dir / "synthetic"
        if not synth.exists():
            continue
        for filled in sorted(synth.glob(f"*{suffix}")):
            src = find_source(filled, type_dir, suffix)
            if src is None:
                print(f"  ! no source for {filled.name}, skipping")
                continue
            work.append((type_name, src, filled))
    if args.limit:
        work = work[:args.limit]
    print(f"Evaluating {len(work)} filled docs with {args.model} ({args.workers} workers)")

    ts = datetime.now().strftime("%Y%m%d_%H%M%S")
    out_dir = RUNS / ts
    out_dir.mkdir(parents=True, exist_ok=True)

    t0 = time.time()
    results: list[GradeRow] = []
    def _job(type_name: str, src: Path, filled: Path) -> GradeRow:
        try:
            g = grade_one(src, filled, args.model)
            return GradeRow(
                type=type_name,
                filled_filename=filled.name,
                source_filename=src.name,
                form_fidelity=int(g.get("form_fidelity", 0)),
                signature_realism=int(g.get("signature_realism", 0)),
                checkbox_correctness=int(g.get("checkbox_correctness", 0)),
                overall_grade=int(g.get("overall_grade", 0)),
                reasoning=str(g.get("reasoning", "")).strip(),
            )
        except Exception as e:
            return GradeRow(
                type=type_name, filled_filename=filled.name, source_filename=src.name,
                form_fidelity=0, signature_realism=0, checkbox_correctness=0, overall_grade=0,
                reasoning="", error=f"{type(e).__name__}: {e}",
            )

    with ThreadPoolExecutor(max_workers=args.workers) as ex:
        futs = [ex.submit(_job, t, s, f) for t, s, f in work]
        for i, fut in enumerate(as_completed(futs), 1):
            row = fut.result()
            results.append(row)
            tag = f"err {row.error}" if row.error else f"overall={row.overall_grade} fid={row.form_fidelity} sig={row.signature_realism} chk={row.checkbox_correctness}"
            print(f"  [{i}/{len(work)}] {row.display_name()}  {tag}", flush=True)

    # Sort by overall desc, then type
    results.sort(key=lambda r: (-r.overall_grade, r.type, r.filled_filename))

    # CSV
    csv_path = out_dir / "grades.csv"
    with csv_path.open("w", newline="") as f:
        fields = ["type", "filled_filename", "source_filename",
                  "overall_grade", "form_fidelity", "signature_realism",
                  "checkbox_correctness", "reasoning", "error"]
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        for r in results:
            w.writerow({k: getattr(r, k) for k in fields})

    # Markdown
    md_path = out_dir / "grades.md"
    with md_path.open("w") as f:
        f.write(f"# Filled-doc evaluation — {ts}\n\n")
        f.write(f"Model: `{args.model}`  ·  Docs: {len(results)}  ·  Wall: {time.time()-t0:.0f}s\n\n")
        f.write("Rubrics (1-10): **fid** = form fidelity, **sig** = signature realism, **chk** = checkbox correctness.  ")
        f.write("`0` for sig/chk means \"not applicable to this page\".\n\n")
        # group averages
        f.write("## Per-type averages\n\n| Type | n | overall | fid | sig (excl 0) | chk (excl 0) |\n|---|---:|---:|---:|---:|---:|\n")
        by_type: dict[str, list[GradeRow]] = {}
        for r in results:
            by_type.setdefault(r.type, []).append(r)
        for tname, rows in sorted(by_type.items()):
            n = len(rows)
            avg = lambda key: sum(getattr(r, key) for r in rows) / n if n else 0
            sig_vals = [r.signature_realism for r in rows if r.signature_realism > 0]
            chk_vals = [r.checkbox_correctness for r in rows if r.checkbox_correctness > 0]
            sig_avg = sum(sig_vals)/len(sig_vals) if sig_vals else 0
            chk_avg = sum(chk_vals)/len(chk_vals) if chk_vals else 0
            f.write(f"| `{tname}` | {n} | {avg('overall_grade'):.1f} | {avg('form_fidelity'):.1f} | {sig_avg:.1f} | {chk_avg:.1f} |\n")
        f.write("\n## Per-doc grades (sorted high→low)\n\n")
        f.write("| Overall | fid | sig | chk | Doc | Reasoning |\n|---:|---:|---:|---:|---|---|\n")
        for r in results:
            if r.error:
                f.write(f"| ERR | - | - | - | `{r.display_name()}` | {r.error} |\n")
            else:
                reason = r.reasoning.replace("|", "\\|").replace("\n", " ")
                f.write(f"| {r.overall_grade} | {r.form_fidelity} | {r.signature_realism} | {r.checkbox_correctness} | `{r.display_name()}` | {reason} |\n")

    # Console summary
    print(f"\nWrote:\n  {csv_path.relative_to(REPO)}\n  {md_path.relative_to(REPO)}")
    if results:
        graded = [r for r in results if not r.error]
        if graded:
            overall_mean = sum(r.overall_grade for r in graded) / len(graded)
            print(f"\nMean overall grade across {len(graded)} docs: {overall_mean:.2f}/10")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
